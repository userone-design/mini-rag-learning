"""

1.简单行列索引
2.列表索引
3.范围索引
4.布尔索引
5.多维索引
1 3 5
"""
import torch
torch.manual_seed(24)
t1 = torch.randint(1,10,(5,5))
print(f"t1:{t1}")
print("-"*30)
 #1.简单行列索引 [行，列] 获取第二行
print(t1[1])
print(t1[1,:])

# 2.列表索引 
# 返回（0，1）（1，2）两个位置的元素
print(t1[[0,1],[1,2]])
print("-"*30)
# 返回（1,2）（3,4）两个位置的元素
print(t1[[1,3],[2,4]])
print("-"*30)
# 返回第0，1行的1，2列 共4个位置的元素
print(t1[[[0],[1]],[1,2]])
print("-"*30)

#3.范围索引
#前3行前2列
print(t1[:3,:2])
print("-"*30)
#第二行到最后一行 前两列
print(t1[1:,:2])
print("-"*30)
#所有奇数行偶数列
print(t1[1::2,0::2])#:2步长为2
print("-"*30)

#4.布尔索引
#第3列大于5的行数据
print(t1[t1[:,2]>5])
print("-"*30)
#第2行大于5的列数据
print(t1[:,t1[1]>5])


#5.多维索引
#2个3行4列的矩阵
t2 = torch.randint(1,10,(2,3,4))
print(f"t2:{t2}")
print("-"*30)

#获取0轴上的第一个数据
print(t2[0,:,:])
print("-"*30)

#获取1轴上的第一个数据
print(t2[:,0,:])
print("-"*30)

#获取2轴上的第一个数据
print(t2[:,:,0])
print("-"*30)




